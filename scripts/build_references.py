def build_all():
    files = {}
    for build in (camera_moves, phrase_map, look_recipes):
        files.update(build())
    for rel, text in files.items():
        assert len(text.splitlines()) <= MAX_LINES, f"{rel} is longer than {MAX_LINES} lines"
    return files


def leftover(expected):
    """Generated files (they carry the note) that the current layout does not write."""
    return sorted(p.relative_to(REFERENCES).as_posix() for p in REFERENCES.rglob("*.md")
                  if p.relative_to(REFERENCES).as_posix() not in expected and NOTE in p.read_text(encoding="utf-8"))


def main():
    files = build_all()
    extra = leftover(files)
    if "--check" in sys.argv:
        stale = [rel for rel, text in files.items()
                 if not (REFERENCES / rel).exists() or (REFERENCES / rel).read_text(encoding="utf-8") != text]
        stale += [f"{rel} (left over from an old layout)" for rel in extra]
        if stale:
            print("stale: " + ", ".join(stale))
            return 1
        return 0
    for rel, text in files.items():
        path = REFERENCES / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text, encoding="utf-8")
        print(f"wrote {path}")
    for rel in extra:
        (REFERENCES / rel).unlink()
        print(f"removed {REFERENCES / rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
