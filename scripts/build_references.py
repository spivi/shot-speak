def technique_block(tech_id, t):
    out = [f"## {t['pro_term']}", "", f"`id: {tech_id}`", "",
           f"- **Plain words:** {t['plain']}",
           f"- **Camera movement:** {t['movement']}.",
           f"- **Camera placement:** {t['placement']}.",
           f"- **Lens:** {t['lens']}. {t['lens_why']}",
           f"- **Default light:** {C.LIGHTS[t['light'][0]]['name']}. Second choice: {C.LIGHTS[t['light'][1]]['name']}.",
           f"- **Default grade:** {C.GRADES[t['grade'][0]]['name']}. Second choice: {C.GRADES[t['grade'][1]]['name']}.",
           f"- **Speed:** {C.SPEEDS[t['speed']]['name']}. **Length:** {t['duration']}.",
           f"- **The viewer feels:** {t['feel']}",
           f"- **Choose it when:** {t['when']}",
           "- **Risks with AI video generators:**"] + [f"  - {r}" for r in t["risks"]] + [
           "- **AI look it avoids:** " + "; ".join(C.SLOP_BY_ID[s]["tell"] for s in t["slop_avoids"]) + "."]
    return out


def look_block(look_id, look):
    also = "; ".join(C.TECHNIQUES[t]["pro_term"] for t in look["also"])
    return [f"## {look['name']}", "", f"`id: {look_id}`", "", "**What makes that look:**", ""] + [
        f"- {m}" for m in look["makes"]] + ["",
        f"- **Shot:** {C.TECHNIQUES[look['technique']]['pro_term']} (`{look['technique']}`).",
        f"- **Light:** {C.LIGHTS[look['light']]['name']}.",
        f"- **Grade:** {C.GRADES[look['grade']]['name']}.",
        f"- **Prompt words:** {look['clause']}.",
        f"- **Other shots of this look:** {also}."]


def see_also(items):
    return ["## See also", ""] + [f"- [{text}]({path}): {why}" for text, path, why in items]


def page(title, intro, blocks, items):
    """One file: heading, note, intro, then the blocks, then See also. Returns the lines."""
    return [f"# {title}", "", NOTE, ""] + intro + [""] + blocks + ["", *see_also(items)]


def pages(slug, title, intro, blocks, items):
    """Pack the blocks into as few files as fit in MAX_LINES. Same input, same files. Returns [(name, lines)]."""
    def build(chunk, n):
        name = f"{slug}.md" if n == 1 else f"{slug}-{n}.md"
        heading = title if n == 1 else f"{title} ({n})"
        body = []
        for block in chunk:
            body += (block + [""])
        return name, page(heading, intro, body[:-1], items)

    chunks, current = [], []
    for block in blocks:
        trial = current + [block]
        flat = [x for b in trial for x in b + [""]][:-1]
        if current and len(page(title, intro, flat, items)) > MAX_LINES:
            chunks.append(current)
            current = [block]
        else:
            current = trial
    if current:
        chunks.append(current)
    out = [build(chunk, n) for n, chunk in enumerate(chunks, 1)]
    for name, lines in out:
        assert len(lines) <= MAX_LINES, f"{name} has {len(lines)} lines: one block is too long"
    return out


def grouped(groups, catalogue, fallback):
    """The groups, in order, with every catalogue id placed once. An id in no group goes to the fallback."""
    named = [i for g in groups for i in g[3]]
    unknown = [i for i in named if i not in catalogue]
    assert not unknown, f"unknown ids in a group: {unknown}"
    assert len(named) == len(set(named)), "an id is in 2 groups"
    rest = [i for i in catalogue if i not in named]
    return list(groups) + ([fallback + (rest,)] if rest else [])


