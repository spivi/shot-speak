    """Returns {relative path: text} for camera/moves/."""
    files, rows = {}, []
    groups = grouped(MOVE_GROUPS, C.TECHNIQUES, ("more-moves", "More moves", "no other group fits"))
    for slug, title, when, ids in groups:
        intro = [f"Read this file when {when}.",
                 "Each entry is 1 complete recipe. The `id` is the value for `--techniques`."]
        items = [("All camera moves", "index.md", "the other groups"),
                 ("Camera placement", "../placement.md", "you set height, side and distance"),
                 ("Lens guide", "../lens.md", "you explain the lens"),
                 ("Speed guide", "../speed.md", "you explain the speed"),
                 ("Phrase map", "../../language/phrase-map.md", "the user's words are vague")]
        blocks = [technique_block(i, C.TECHNIQUES[i]) for i in ids]
        made = pages(slug, f"Camera moves: {title}", intro, blocks, items)
        names = "; ".join(f"{C.TECHNIQUES[i]['pro_term']} (`{i}`)" for i in ids)
        for name, lines in made:
            files[f"camera/moves/{name}"] = "\n".join(lines) + "\n"
        rows.append(f"- [{title}]({made[0][0]}): Read when {when}. Holds: {names}.")
    index = ["# Camera moves and shot types", "", NOTE, "",
             "Read the group that matches the user's words. Each entry is 1 complete recipe with the pro term, the plain",
             "meaning and the generator risks. The `id` is the value for `--techniques`.", ""] + rows + [
             "", *see_also([("Camera", "../index.md", "placement, lens and speed"),
                            ("Phrase map", "../../language/phrase-map.md", "the user's words are vague")])]
    files["camera/moves/index.md"] = "\n".join(index) + "\n"
    return files


